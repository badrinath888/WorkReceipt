"""Build identity: proves which source a running app (source checkout or packaged .app) was built from.

The fingerprint is a SHA-256 over the files that make up the running product (runtime Python modules and the UI), so
  * it changes whenever product code changes, and a docs-only commit does not make an app look stale;
  * a packaged app carries the fingerprint baked in at build time (`_build_info.py`, written by desktop/build_macos.sh), so an .app built before
    a fix reports a DIFFERENT fingerprint from the repo that contains the fix, and validation refuses it.
Standard library only."""
import hashlib, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME_FILES = ("app_core.py", "client_safe.py", "workreceipt.py", "workreceipt_app.py", "buildinfo.py", "desktop/main.py", "desktop/pdf_mac.py")
RUNTIME_DIRS = ("ui",)


def runtime_paths(root=HERE):
    out = [f for f in RUNTIME_FILES]
    for d in RUNTIME_DIRS:
        for base, _dirs, files in os.walk(os.path.join(root, d)):
            out += [os.path.relpath(os.path.join(base, f), root).replace(os.sep, "/") for f in files if not f.startswith(".")]
    return sorted(set(out))


def source_fingerprint(root=HERE):
    """Hex SHA-256 of (relative path, content) for every runtime file, or None if any is missing (e.g. inside a packaged app)."""
    h = hashlib.sha256()
    for rel in runtime_paths(root):
        p = os.path.join(root, rel)
        try:
            with open(p, "rb") as f:
                data = f.read()
        except OSError:
            return None
        h.update(rel.encode() + b"\0" + hashlib.sha256(data).digest())
    return h.hexdigest()


def git_state(root=HERE):
    """(short sha | '', dirty bool). Informational only; the fingerprint is what is compared."""
    try:
        sha = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=10).stdout.strip()
        dirty = bool(subprocess.run(["git", "-C", root, "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True, timeout=10).stdout.strip())
        return sha, dirty
    except (OSError, subprocess.SubprocessError):
        return "", False


def current(version, root=HERE):
    """{version, fingerprint, git, dirty, source}. A frozen (packaged) app reports what was baked in; anything else reports its live source.
    A packaged app with nothing baked in, or a source tree with missing files, reports fingerprint 'unknown', which never matches."""
    if getattr(sys, "frozen", False):
        try:
            import _build_info as b                                # noqa: PLC0415  (only exists in packaged builds)
            return {"version": version, "fingerprint": b.FINGERPRINT, "git": b.GIT, "dirty": bool(b.DIRTY), "source": "packaged build", "built_at": b.BUILT_AT}
        except Exception:                                          # noqa: BLE001
            return {"version": version, "fingerprint": "unknown", "git": "", "dirty": False, "source": "packaged build without build identity"}
    fp = source_fingerprint(root)
    sha, dirty = git_state(root)
    return {"version": version, "fingerprint": fp or "unknown", "git": sha, "dirty": dirty, "source": "source checkout"}


def compare(reported, expected_fingerprint):
    """-> (is_current, message). `reported` is a current() dict (or None / garbage from an app too old to report one)."""
    fp = reported.get("fingerprint") if isinstance(reported, dict) else None
    if not isinstance(fp, str) or not fp or fp == "unknown":
        return False, "the app does not report which source it was built from (it predates build identity or was built without it)"
    if fp != expected_fingerprint:
        return False, f"built from different source (app {fp[:12]} / git {str(reported.get('git') or '?')[:12]}, this checkout {expected_fingerprint[:12]})"
    return True, f"built from this checkout's source ({fp[:12]}, git {reported.get('git') or '?'}{', uncommitted changes' if reported.get('dirty') else ''})"


STALE_HELP = "Rebuild it: desktop/build_macos.sh (it deletes build/ and dist/ first), then run scripts/validate_macos.sh again."


def write_baked(version, root=HERE, path=None):
    """Called by desktop/build_macos.sh just before PyInstaller: bakes the fingerprint into _build_info.py (git-ignored, removed after the build)."""
    import time
    fp = source_fingerprint(root)
    if not fp:
        raise SystemExit("buildinfo: runtime files are missing; cannot compute the build fingerprint")
    sha, dirty = git_state(root)
    path = path or os.path.join(root, "_build_info.py")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# generated by buildinfo.write_baked; never edit or commit\nVERSION = {version!r}\nFINGERPRINT = {fp!r}\nGIT = {sha!r}\nDIRTY = {dirty!r}\nBUILT_AT = {time.strftime('%Y-%m-%dT%H:%M:%S%z')!r}\n")
    return path


def read_app_build(binary, timeout=30):
    """Ask a built app which source it came from WITHOUT opening a window: run `<binary> --build-info <tmpfile>`. Returns the dict, or None when the
    app gave no answer in time (an app built before this feature ignores the flag and starts its GUI; it is killed after `timeout` seconds)."""
    import signal, tempfile, time
    fd, tmp = tempfile.mkstemp(prefix="wr-buildinfo-", suffix=".json"); os.close(fd)
    p = None
    try:
        p = subprocess.Popen([binary, "--build-info", tmp], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
        t0 = time.time()
        while p.poll() is None and time.time() - t0 < timeout:
            time.sleep(0.2)
        if p.poll() is None:
            return None
        with open(tmp, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError, subprocess.SubprocessError):
        return None
    finally:
        if p is not None and p.poll() is None:
            try:
                os.killpg(p.pid, signal.SIGKILL)
            except (OSError, ProcessLookupError):
                pass
        try:
            os.remove(tmp)
        except OSError:
            pass


def check_app(binary, root=HERE, timeout=30):
    """-> (is_current, message, reported dict | None). A stale or unidentifiable app is NOT current."""
    expected = source_fingerprint(root)
    if not expected:
        return False, "cannot compute this checkout's fingerprint (runtime files missing)", None
    got = read_app_build(binary, timeout)
    ok, msg = compare(got, expected)
    return ok, msg, got


if __name__ == "__main__":
    import app_core
    cmd = sys.argv[1] if len(sys.argv) > 1 else "show"
    if cmd == "bake":
        print(write_baked(app_core.VERSION))
    elif cmd == "check-app" and len(sys.argv) > 2:                    # exit 0 current, 1 stale or unidentifiable
        ok, msg, _ = check_app(sys.argv[2])
        print(("CURRENT: " if ok else "STALE: ") + msg + ("" if ok else ". " + STALE_HELP))
        sys.exit(0 if ok else 1)
    else:
        print(json.dumps(current(app_core.VERSION), indent=1))
